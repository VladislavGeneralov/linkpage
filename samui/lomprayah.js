// ---------- скоростной катамаран Lomprayah (линия Самуи — Панган) ----------
// По refs/ferry_samui_phangan: 02 (вид с кормы-борта на ходу), 01 (сбоку), 04 (верхняя палуба), 06 (пирс Маенам).
// Два узких корпуса с туннелем между ними, над ними — общий мост-палуба во всю ширину. Борта корпусов белые, по ним
// от носа к корме идут синяя и красная «волны» Lomprayah. Главная палуба: салон с длинной тёмной лентой окон,
// нос — низкий скошенный «козырёк» из тёмного стекла; в корме салона — открытая палуба под навесом второго яруса.
// Второй ярус: салон с ходовым мостиком впереди, сзади открытая площадка с белыми контейнерами плотов вдоль лееров
// и синим трапом. Сверху — открытая палуба с леерами, сиденьями, мачтой с радаром и флагом на корме.
// В транцах корпусов — трапы, между корпусами тёмный туннель, на кормовой стенке — порт приписки BANGKOK.
// Высоты ярусов — в рост человека; длина по умолчанию 30 м (настоящие суда Lomprayah — около 37–40 м; длина судов
// в игре — в масштабе машин, с тем же сжатием, что у парома Seatran). Оси: +x — нос, y — вверх от воды, z — борт.
function boatLomprayah(o = {}) {
  const S = shipyard(), L = o.L || 30, B = o.B || 9;
  const white = '#fbfbf8', glass = '#1a2430', blue = '#2a3f9e', red = '#c42032', deckBlue = '#2f63c8';
  const hb = 2.3, hz = B / 2 - hb / 2;                            // ширина корпуса и где его ось
  const free = 2.0;                                               // высота борта корпусов над водой
  // --- два корпуса: строятся отдельно и переносятся на свои места; по наружным бортам — синяя и красная «волны»
  for (const s of [-1, 1]) {
    const T = shipyard();
    const H = T.hull({ L, B: hb, free, draft: 1.0, full: 0.5, bowFrom: 0.62, entry: 1.6, bowRise: 0.5, rake: 1.4, stern: 0.88, sternTo: 0.06,
      wall: 0, bottom: '#26304a', boot: white, side: white, sheer: white, deck: '#d8dade', bootTop: 0.35, sheerH: 0.12 });
    const N = 40;
    for (let i = 0; i < N; i++) {                                                             // синяя волна: широкая, поднимается к носу
      const u = i / (N - 1), x = -L * 0.47 + u * L * 0.86, y = 1.15 + 0.4 * u + 0.32 * Math.sin(u * 7);
      const dy = (0.45 + 0.28 * 7 * Math.cos(u * 7)) / (L * 0.86);
      T.box(L * 0.86 / (N - 1) + 0.08, 0.72 - 0.3 * u, 0.04, x, y, s * (H.side(x, y) + 0.03), blue, Math.atan(dy));
    }
    for (let i = 0; i < N; i++) {                                                             // красная под ней, ближе к воде
      const u = i / (N - 1), x = -L * 0.47 + u * L * 0.8, y = 0.6 + 0.4 * u + 0.3 * Math.sin(u * 7 + 1.4);
      const dy = (0.4 + 0.25 * 7 * Math.cos(u * 7 + 1.4)) / (L * 0.8);
      T.box(L * 0.8 / (N - 1) + 0.08, 0.5 - 0.18 * u, 0.04, x, y, s * (H.side(x, y) + 0.03), red, Math.atan(dy));
    }
    T.box(0.9, 1.2, 0.08, -L / 2 + 0.35, 0.7, 0, '#8a9098');                                  // трап в транце
    for (let k = 0; k < 4; k++) T.box(0.95, 0.05, 0.12, -L / 2 + 0.3, 0.25 + k * 0.32, 0, '#b8bec6');
    const m = T.mesh(), p = m.geometry.attributes.position, c = m.geometry.attributes.color;
    for (let i = 0; i < p.count; i += 3) {
      const v = [0, 1, 2].map((k) => [p.getX(i + k), p.getY(i + k), p.getZ(i + k) + s * hz]);
      S.tri(v[0], v[1], v[2], new THREE.Color(c.getX(i), c.getY(i), c.getZ(i)));
    }
  }
  const hw = B / 2;
  // --- мост между корпусами: сверху палуба, снизу тёмный туннель; нос моста — клин к носам корпусов
  const xb0 = -L / 2 + 0.4, xb1 = L / 2 - 3.2;
  S.box(xb1 - xb0, free - 1.0, 2 * (hz - 0.2), (xb0 + xb1) / 2, (free + 1.0) / 2, 0, white);
  S.box(xb1 - xb0, 0.05, 2 * (hz - 0.3), (xb0 + xb1) / 2, 1.0, 0, '#1c2028');
  S.box(0.06, 0.9, 2 * (hz - 0.9), -L / 2 + 0.38, 1.25, 0, '#1c2028');                        // туннель с кормы
  S.house(xb1 - 0.2, L / 2 - 0.4, 1.0, free + 0.3, hz - 0.2, hz - 0.2, 0, 1.6, white);               // клин моста к носам корпусов
  // --- главная палуба: салон с лентой окон и тёмным скошенным носом
  const d0 = free, d1 = d0 + 2.4;
  const xc0 = -L / 2 + L * 0.2, xc1 = L / 2 - 1.0, rakeF = 5.2;
  S.house(xc0, xc1, d0, d1, hw - 0.02, hw - 0.32, rakeF, 0, white);
  S.windows(xc0 + 0.9, xc1 - rakeF * 0.55, d0 + 1.45, 1.05, hw - 0.17, false, 0, glass);
  for (const s of [-1, 1]) S.text('LOMPRAYAH', xc0 + 4.5, d0 + 0.75, s * (hw + 0.01), 0.1, '#2a2a30', s);
  { const ang = Math.atan2(rakeF, d1 - d0), len = (d1 - d0) * 0.62 / Math.cos(ang);            // тёмный «козырёк» на скате носа
    const yc = d0 + (d1 - d0) * 0.55, xc = xc1 - rakeF * 0.55;
    S.box(0.06, len, 2 * (hw - 0.55), xc + 0.04, yc, 0, glass, ang);
  }
  // открытая кормовая палуба главного яруса: синий настил, леера, стойки навеса
  S.box(xc0 - xb0 - 0.2, 0.06, 2 * hw - 0.4, (xb0 + xc0) / 2, d0 + 0.03, 0, deckBlue);
  S.rail(xb0 + 0.2, xc0 - 0.1, d0, hw - 0.12, white, 1.0, 1.2);
  for (const z of [-(hw - 0.15), hw - 0.15]) for (const x of [xb0 + 0.8, (xb0 + xc0) / 2]) S.box(0.12, d1 - d0, 0.12, x, (d0 + d1) / 2, z, white);
  S.text('BANGKOK', -L / 2 + 0.33, d0 - 0.15, (x, y) => 0, 0.12, '#1c2028', -1);
  // --- второй ярус: настил над кормовой палубой, салон с мостиком, площадка с плотами и трапом
  const d2 = d1 + 0.12, xs0 = -L * 0.06, xs1 = xc1 - rakeF - 0.4, d3 = d2 + 2.2;
  S.box(xc1 - rakeF - xb0 + 0.2, 0.14, 2 * hw - 0.3, (xb0 + xc1 - rakeF) / 2 + 0.1, d1 + 0.05, 0, '#e2e4e8');
  S.box(xs0 - xb0 - 0.6, 0.06, 2 * hw - 1.0, (xb0 + xs0) / 2 + 0.3, d2 + 0.02, 0, deckBlue);
  S.house(xs0, xs1, d2, d3, hw - 0.7, hw - 1.0, 1.6, 0, white);
  S.windows(xs0 + 0.8, xs1 - 1.7, d2 + 1.2, 0.8, hw - 0.82, false, 0, glass);
  { const ang = Math.atan2(1.6, d3 - d2);                                                    // окна мостика на скате
    S.box(0.06, 0.9 / Math.cos(ang), 2 * (hw - 1.3), xs1 - 0.75, d2 + 1.35, 0, glass, ang); }
  S.rail(xb0 + 0.5, xs0, d2, hw - 0.3, white, 1.0, 1.2);
  S.box(0.05, 1.0, 2 * hw - 0.6, xb0 + 0.5, d2 + 0.5, 0, white);
  for (let x = xb0 + 2.2; x < xs0 - 1.2; x += 1.6) for (const s of [-1, 1]) S.tube(x, d2 + 0.55, d2 + 1.15, s * (hw - 0.55), 0.32, 0.32, '#eef0f2', 8);   // контейнеры плотов
  for (const s of [-1, 1]) S.tube(xs0 - 1.0, d2 + 0.6, d2 + 1.1, s * (hw - 0.3), 0.24, 0.24, '#e86a1a', 6);                // спасательные круги
  S.rod([xs0 - 0.4, d2, 1.4], [xs0 + 1.4, d3, 1.4], 0.7, deckBlue);                         // синий трап на верхнюю палубу
  // --- верхняя открытая палуба: настил, леера, скамьи, мачта с радаром, флаг
  const xt0 = xs0 - 2.2, xt1 = xs1 - 1.6;
  S.box(xt1 - xt0, 0.14, 2 * (hw - 0.9), (xt0 + xt1) / 2, d3, 0, '#e2e4e8');
  for (let x = xs0 - 1.7; x < xs0 - 0.2; x += 1) for (const z of [-1.3, 1.3]) S.box(0.12, 1.0, 0.12, x, d2 + 0.5 + 1.1, z, white);
  S.rail(xt0, xt1, d3 + 0.07, hw - 0.95, white, 1.0, 1.1);
  S.box(0.05, 1.0, 2 * (hw - 0.95), xt0, d3 + 0.57, 0, white);
  for (let x = xt0 + 1.0; x < xt1 - 2.5; x += 1.2) for (const z of [-1.6, 0, 1.6]) S.box(0.5, 0.42, 1.1, x, d3 + 0.28, z, deckBlue);   // скамьи
  const mx = xt1 - 1.2;
  S.box(0.18, 2.2, 0.18, mx, d3 + 1.1, 0, '#e8eaee');
  S.box(0.25, 0.12, 1.8, mx + 0.1, d3 + 2.05, 0, '#eef0f2'); S.box(0.3, 0.3, 0.3, mx, d3 + 1.75, 0, '#d0d2d6');   // радар и огонь
  for (const s of [-1, 1]) S.box(0.3, 0.3, 0.35, xt1 - 0.3, d3 + 0.3, s * (hw - 1.3), '#d0d2d6');                // прожекторы
  S.box(0.06, 1.6, 0.06, xt0 + 0.2, d3 + 0.85, hw - 1.2, '#d0d2d6');
  thaiFlag(S, xt0 + 0.2, d3 + 1.65, hw - 1.2, 0.8);
  return S.mesh();
}
