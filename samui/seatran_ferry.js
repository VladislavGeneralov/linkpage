// ---------- большой автопаром Seatran Ferry 10 (стоит у пирса Seatran в Натоне) ----------
// По refs/seatran_ferry_nathon: 01 (вид с носа), 03–04 (он же с кормы и сбоку у Донсака).
// Высокий белый корпус с красным низом, острый нос с развалом и фальшбортом на баке. Автомобильная палуба закрыта:
// борт глухой, по нему крупная синяя надпись SEATRAN и номер у кормы. Над корпусом вровень с бортом — два
// пассажирских яруса с рядами квадратных окон. Наверху открытая палуба с леерами, красными ящиками плотов,
// шлюпками и серым кожухом трубы с эмблемой Seatran. В носу — два яруса: белая рубка с иллюминаторами и дверью,
// над ней ходовой мостик во всю ширину судна: стёкла по кругу завалены наружу, крыша-козырёк, крылья закрыты.
// На крыше мостика леера, серая мачта на подкосах с двумя площадками, антеннами радаров, реем и огнями,
// белый шар спутниковой антенны, штыревые антенны и малая мачта. Под мостиком в лобовой стенке — открытая
// галерея на стойках и жёлтый трап на верхнюю палубу. На корме открытая площадка, серые башни подъёма
// аппарели с перекладиной, поднятая аппарель в транце, две тонкие выхлопные трубы и высокая мачта.
// Высоты ярусов — в рост человека. Длина 60 м — в масштабе машин, а не острова (настоящий — 84 м): решение Влада.
function boatSeatranFerry(o = {}) {
  const S = shipyard(), L = o.L || 60, B = o.B || 11, num = o.num || '10';
  const blue = '#1d4fa8', white = '#eef0f2', house = '#f4f4f2', red = '#c2242a', grey = '#7c838c', glass = '#1c2a36';
  const H = S.hull({ L, B, free: 3.0, draft: 1.3, full: 0.85, bowFrom: 0.80, entry: 1.8, bowRise: 1.4, rake: 3.0, stern: 0.96, sternTo: 0.08, n: 24,
    wall: 0.8, bottom: '#7e181c', boot: red, side: white, sheer: white, deck: '#8a9098', bootTop: 0.9, sheerH: 0.2 });
  const hw = B / 2, deckY = 2.2;                                  // палуба бака и кормы
  const xs0 = -L / 2 + L * 0.13, xs1 = L * 0.31;                  // надстройка: от кормовой площадки до короткого бака
  const d0 = 2.8, d1 = 5.0, d2 = 7.0, frontRake = 0.6, tilt = Math.atan2(frontRake, d2 - d0);
  // --- два пассажирских яруса вровень с бортом; лобовая стенка чуть завалена назад
  S.house(xs0, xs1, d0, d2, hw - 0.03, hw - 0.03, frontRake, 0, house);
  for (const s of [-1, 1]) {
    S.box(xs1 - xs0 - 0.6, 0.07, 0.06, (xs0 + xs1) / 2 - 0.3, d1, s * hw, '#c8ccd0');             // поясок между ярусами
    for (const y of [d0 + 1.25, d1 + 1.1]) {                                                   // квадратные окна группами по пять
      let n = 0;
      for (let x = xs0 + 1.3; x < xs1 - 2.0; x += 1.45, n++) if (n % 6 !== 5) S.box(0.85, 0.75, 0.06, x, y, s * (hw + 0.01), glass);
    }
    // надпись и номер — по обшивке корпуса, под окнами
    S.text('SEATRAN', L * 0.07, 2.85, (x, y) => H.side(x, y), 0.38, blue, s);
    S.text(num, -L * 0.31, 2.85, (x, y) => H.side(x, y), 0.38, blue, s);
    S.box(0.5, 0.7, 0.12, L / 2 - 2.6, 2.5, s * (H.side(L / 2 - 2.6, 2.5) + 0.05), '#2a2c30');     // якорь в клюзе
    S.box(xs1 - xs0, 0.09, 0.07, (xs0 + xs1) / 2, d0 + 0.1, s * (hw + 0.01), '#c8ccd0');          // привальный брус по стыку корпуса и надстройки
  }
  // лобовая стенка: тёмный проём швартовной палубы под мостиком и ряд окон второго яруса
  S.box(0.06, 1.35, B - 2.4, xs1 - 0.2 + 0.05, d0 + 1.35, 0, '#22303c', tilt);
  S.box(1.7, 0.1, B - 0.8, xs1 + 0.45, d1, 0, '#9aa0a8');                                       // площадка над галереей
  for (const z of [-(hw - 0.7), -1.2, 1.2, hw - 0.7]) S.box(0.14, d1 - d0 + 0.5, 0.14, xs1 + 1.15, (d1 + d0 - 0.5) / 2, z, house);
  S.rail(xs1 + 0.2, xs1 + 1.25, d1 + 0.05, hw - 0.5, house, 0.9, 1.1);
  S.rod([xs1 + 0.75, d1 + 0.1, -(hw - 1.0)], [xs1 + 0.2, d2 + 0.05, -(hw - 3.0)], 0.5, '#d8b040');       // жёлтый трап на верхнюю палубу
  S.box(0.06, 0.75, B - 1.6, xs1 - 0.47 + 0.05, d1 + 1.1, 0, glass, tilt);
  for (let z = -hw + 1.9; z < hw - 1.5; z += 1.3) S.box(0.08, 0.8, 0.14, xs1 - 0.47 + 0.06, d1 + 1.1, z, house, tilt);
  // кормовая стенка: въезд на автомобильную палубу
  S.box(0.06, 2.6, B - 2.2, xs0 - 0.02, deckY + 1.3, 0, '#1c222a');
  // --- верхняя палуба: настил, леера, красные ящики плотов, рубка с эмблемой
  S.box(xs1 - xs0 + 0.3, 0.12, B + 0.1, (xs0 + xs1) / 2 - 0.2, d2, 0, '#9aa0a8');
  const xb0 = xs1 - 10.4, xb1 = xs1 - 1.3, d3 = d2 + 2.1;         // рубка под мостиком: от и до, высота её крыши
  S.rail(xs0, xs1 - 0.7, d2 + 0.06, hw - 0.1, house, 1.0, 1.6);
  S.box(0.05, 1.0, B - 0.2, xs1 - 0.7, d2 + 0.56, 0, house);
  S.box(0.05, 1.0, B - 0.2, xs0, d2 + 0.56, 0, house);
  for (let x = xs0 + 3.5; x < xb0 - 3; x += 2.6) for (const s of [-1, 1]) S.box(1.5, 0.7, 0.9, x, d2 + 0.45, s * (hw - 1.1), '#c8402c');
  S.house(-L * 0.14, -L * 0.04, d2 + 0.06, d2 + 2.3, 1.5, 1.35, 0.3, 0.9, grey);                 // серый кожух трубы со скосом к корме
  for (const s of [-1, 1]) {                                                                  // эмблема: красный штурвал с синей серединой
    const ex = -L * 0.08, ey = d2 + 1.25;
    S.box(1.1, 1.1, 0.05, ex, ey, s * 1.47, '#c8242c'); S.box(1.1, 1.1, 0.05, ex, ey, s * 1.47, '#c8242c', Math.PI / 4);
    S.box(0.74, 0.74, 0.06, ex, ey, s * 1.48, '#eef0f2', Math.PI / 4); S.box(0.5, 0.5, 0.07, ex, ey, s * 1.49, blue);
  }
  for (const x of [xs0 + 6, xb0 - 2.5]) for (const s of [-1, 1]) S.tube(x, d2 + 0.45, d2 + 1.0, s * (hw - 0.14), 0.3, 0.3, '#e86a1a', 6);   // спасательные круги
  for (const s of [-1, 1]) {                                                                  // шлюпка на шлюпбалках у мостика
    S.box(3.0, 0.8, 1.1, xb0 - 2.4, d2 + 1.5, s * (hw - 0.75), '#e86a1a');
    for (const x of [xb0 - 3.6, xb0 - 1.2]) S.box(0.14, 2.0, 0.14, x, d2 + 1.0, s * (hw - 0.25), '#d0d2d6');
  }
  for (const x of [xs0 + 5, -L * 0.2, L * 0.02]) S.tube(x, d2 + 0.06, d2 + 0.9, 0, 0.3, 0.42, '#d8dade', 8);   // вентиляционные грибки
  // --- рубка под мостиком: уже борта, иллюминаторы и дверь, по бокам проходы
  S.house(xb0, xb1, d2 + 0.06, d3, hw - 1.3, hw - 1.3, 0.15, 0.1, house);
  for (const s of [-1, 1]) {
    for (let x = xb0 + 1.0; x < xb1 - 1.0; x += 1.5) S.box(0.42, 0.42, 0.06, x, d2 + 1.3, s * (hw - 1.28), glass);
    S.box(0.6, 1.6, 0.06, xb0 + 2.5, d2 + 0.9, s * (hw - 1.27), '#8a9098');
    S.tube(xb0 + 4.2, d2 + 0.9, d2 + 1.45, s * (hw - 1.2), 0.28, 0.28, '#c8242c', 6);
  }
  S.house(xb0 - 2.2, xb0 - 0.2, d2 + 0.06, d2 + 1.7, 1.3, 1.3, 0, 0.9, grey);                   // серый вентиляционный кожух за рубкой
  // --- ходовой мостик во всю ширину: стенки завалены наружу, лента окон по кругу, крыша-козырёк
  const xw0 = xs1 - 6.6, xw1 = xs1 - 0.9, wy = d3 + 0.07, wh = 2.25, lean = 0.22, fwd = 0.4;
  S.box(xw1 - xw0 + 1.2, 0.14, B + 0.2, (xw0 + xw1) / 2 - 0.2, d3, 0, '#9aa0a8');               // палуба мостика с крыльями
  S.house(xw0, xw1, wy, wy + wh, hw - 0.3, hw - 0.3 + lean, -fwd, -0.15, house);
  const band = wy + 1.45, bh = 0.85, k = (band - wy) / wh, wz = hw - 0.3 + lean * k;
  for (const s of [-1, 1]) {
    S.box(xw1 - xw0 - 0.3 + fwd * k, bh, 0.06, (xw0 + xw1 + fwd * k) / 2, band, s * (wz + 0.02), glass);
    for (let x = xw0 + 0.9; x < xw1; x += 0.95) S.box(0.1, bh + 0.02, 0.08, x, band, s * (wz + 0.03), house);
  }
  S.box(0.06, bh, 2 * wz - 0.2, xw1 + fwd * k + 0.03, band, 0, glass, -Math.atan2(fwd, wh));
  for (let z = -wz + 0.9; z < wz - 0.4; z += 0.95) S.box(0.08, bh + 0.02, 0.1, xw1 + fwd * k + 0.04, band, z, house, -Math.atan2(fwd, wh));
  S.box(0.06, bh, 2 * wz - 2.4, xw0 - 0.15 * k - 0.03, band, 0, glass);                          // окна в корму
  const roofY = wy + wh + 0.07;
  S.box(xw1 - xw0 + 1.5, 0.14, B + 0.5, (xw0 + xw1) / 2 + 0.35, roofY, 0, '#d8dade');           // крыша с козырьком
  S.rail(xw0 + 0.1, xw1 + 0.2, roofY + 0.07, hw - 0.25, '#b8bec6', 0.9, 1.3);
  for (const x of [xw0 + 0.1, xw1 + 0.2]) { S.box(0.05, 0.05, B - 0.5, x, roofY + 0.97, 0, '#b8bec6'); S.box(0.04, 0.04, B - 0.5, x, roofY + 0.52, 0, '#b8bec6'); }
  // --- мачта: столб на подкосах, две площадки с радарами, рей с антеннами и огнями
  const mast = '#8c949c', mx = xw0 + 2.3, my = roofY + 0.07, mh = 6.2;
  S.tube(mx, my, my + mh, 0, 0.24, 0.16, mast, 6);
  S.rod([mx - 2.0, my, 0], [mx - 0.1, my + 4.0, 0], 0.16, mast);                                // подкос в корму
  for (const s of [-1, 1]) S.rod([mx + 0.2, my, s * 1.3], [mx, my + 3.3, 0], 0.12, mast);
  S.box(1.4, 0.1, 1.3, mx + 0.75, my + 3.1, 0, mast);                                           // нижняя площадка с радаром
  S.box(0.2, 0.4, 0.2, mx + 0.95, my + 3.35, 0, '#d8dade'); S.box(0.2, 0.16, 1.9, mx + 0.95, my + 3.62, 0, '#eef0f2');
  S.box(0.06, 0.5, 1.3, mx + 1.42, my + 3.4, 0, mast);
  S.box(1.3, 0.1, 2.8, mx, my + mh - 0.6, 0, mast);                                             // верхняя площадка
  for (const z of [-1.4, 1.4]) S.box(1.3, 0.5, 0.05, mx, my + mh - 0.3, z, mast);
  S.box(0.2, 0.35, 0.2, mx + 0.2, my + mh - 0.37, 0, '#d8dade'); S.box(0.2, 0.16, 2.3, mx + 0.2, my + mh - 0.12, 0, '#eef0f2');
  S.box(0.1, 0.1, 3.8, mx - 0.1, my + mh + 0.25, 0, mast);                                      // рей
  for (const z of [-1.8, -0.9, 0.9, 1.8]) S.box(0.05, 0.9, 0.05, mx - 0.1, my + mh + 0.7, z, '#d0d2d6');
  S.box(0.07, 1.6, 0.07, mx - 0.1, my + mh + 1.05, 0, '#d0d2d6');
  S.box(0.16, 0.16, 0.16, mx + 0.25, my + 4.6, 0, '#f2f2ea'); S.box(0.16, 0.16, 0.16, mx + 0.25, my + 5.2, 0, '#c8242c');   // ходовые огни
  S.rod([mx, my + mh - 0.6, 0], [xw1 + 0.2, roofY + 1.0, 0], 0.04, '#b8bec6');                  // штаг к носу
  // на крыше: шар спутниковой антенны, малая мачта, штыревые антенны, прожекторы, зелёный ящик
  S.tube(mx + 1.9, my, my + 0.35, -1.9, 0.14, 0.14, '#d0d2d6', 6); S.tube(mx + 1.9, my + 0.35, my + 0.95, -1.9, 0.38, 0.3, '#f4f4f2', 8);
  S.box(0.12, 2.4, 0.12, mx + 2.3, my + 1.2, 2.0, mast); S.box(0.08, 0.08, 1.0, mx + 2.3, my + 2.1, 2.0, mast); S.box(0.3, 0.3, 0.3, mx + 2.3, my + 2.5, 2.0, '#d8dade');
  for (const [x, z, h] of [[xw0 + 0.5, -2.6, 3.6], [xw0 + 0.9, -1.6, 2.8], [xw0 + 0.5, 2.7, 3.0]]) S.box(0.045, h, 0.045, x, my + h / 2, z, '#d0d2d6');
  for (const s of [-1, 1]) { S.box(0.12, 0.5, 0.12, xw1 - 0.3, my + 0.25, s * (hw - 1.2), '#d0d2d6'); S.box(0.4, 0.4, 0.45, xw1 - 0.15, my + 0.65, s * (hw - 1.2), '#eef0f2'); }
  S.box(0.8, 0.55, 0.7, xw0 + 1.0, my + 0.28, 1.4, '#2f7a5a');
  // --- бак: брашпиль, кнехты, флагшток
  const fx = L / 2 - 4.6, fy = H.at(fx).deck;
  S.box(1.3, 0.75, 2.0, fx, fy + 0.38, 0, '#6a7078');
  for (const s of [-1, 1]) { S.box(0.35, 0.5, 0.35, fx + 1.6, H.at(fx + 1.6).deck + 0.25, s * 0.9, '#3a3c40'); S.box(0.35, 0.5, 0.35, fx - 1.2, fy + 0.25, s * 2.2, '#3a3c40'); }
  S.box(0.07, 2.0, 0.07, H.tip[0] - 0.3, H.tip[1] + 1.0, 0, '#d0d2d6');
  // --- корма: площадка, башни аппарели с перекладиной, поднятая аппарель, выхлопные трубы, мачта, флаг
  const tx = -L / 2 + 1.7;
  for (const s of [-1, 1]) {
    S.box(1.1, 5.2, 1.1, tx, deckY + 2.6, s * (hw - 0.85), grey);
    S.tube(xs0 + 0.9, d2, d2 + 2.6, s * (hw - 1.3), 0.3, 0.26, '#3a3c40', 8);
    S.rail(-L / 2 + 0.5, xs0 - 0.4, deckY, hw - 0.12, house, 1.0, 1.4, [s]);
  }
  S.box(0.6, 0.45, B - 1.6, tx, deckY + 5.0, 0, grey);
  S.box(0.3, 3.6, B - 2.6, -L / 2 + 0.5, deckY + 1.85, 0, '#8a9098', -0.1);
  S.box(1.6, 0.9, 1.6, xs0 - 1.6, deckY + 0.45, 0, '#6a7078');                                  // лебёдка
  S.box(0.2, 6.5, 0.2, xs0 + 3.2, d2 + 3.3, 0, '#d0d2d6'); S.box(0.12, 0.12, 2.6, xs0 + 3.2, d2 + 5.4, 0, '#d0d2d6');
  S.box(0.06, 1.8, 0.06, -L / 2 + 0.25, deckY + 1.9 + 3.6 / 2 + 0.6, hw - 1.6, '#d0d2d6');
  thaiFlag(S, -L / 2 + 0.25, deckY + 5.1, hw - 1.6, 0.8);
  return S.mesh();
}
