// ---------- Porsche ----------
// Porsche 911 Turbo (930), бледно-лазурный металлик. Кузов и крылья — обшивка по сечениям; всё, кроме колёс,
// сливается в одну сетку на материал. Размеры сняты с бокового фото (база 2.27 м = 1043 пикселя): длина 4.29 м
// (свесы 0.92 и 1.10 м, с клыками сзади 4.33), высота 1.31 м, ширина 1.775 м по задним аркам.
// Передние крылья — «трубы»: гребень 0.89 м у лобового, полого спускается к фаре (0.84 над осью, 0.77 у фары);
// на скошенном носу каждой лежит большая круглая фара с наклоном назад 26°; капот ниже и лежит между ними;
// бампер выступает на 0.28 м дальше фар. Лобовое начинается сразу за передним колесом (низ 0.89 м), завалено на 37°,
// в плане выгнуто вперёд; крыша — одна дуга с вершиной 1.31 м, от неё выпуклый скат до кормы (1.22 м над задним
// сиденьем, 1.0 м у низа заднего стекла). Подоконник 0.85 м, верх окон 1.19 м; боковое стекло — капля, сходящая
// в точку над задней осью. Задние крылья — раструбы: гребень прижат к кузову, шире всего у кромки арки; арки
// приплюснуты (сзади 0.36 × 0.30 м). Корма скруглена в плане; фонари и красная полоса-катафот стоят прямо над
// бампером (0.48–0.57 м), жёлтый поворотник огибает угол. На крышке мотора — «китовый хвост» с чёрной резиновой
// кромкой и решёткой. Бамперы с чёрной полосой, гармошками и клыками; колёса Fuchs. Нос — к -Z.
const PORSCHE_L = 4.3, PORSCHE_WHEEL_R = 0.315, PORSCHE_AXLE = 1.135;      // колёсная база 2.27 м
function buildPorsche() {
  const car = new THREE.Group(), body = new THREE.Group();        // body качается; колёса остаются на земле
  car.add(body);
  const paint = lambert({ color: 0x6fa6d2 }), glass = lambert({ color: 0x2c3a4c });
  const chrome = lambert({ color: 0xd8dad6 }), dark = lambert({ color: 0x1a1a1a });
  const seam = lambert({ color: 0x34383d }), plate = lambert({ color: 0xe9e9e4 });
  const lensMat = new THREE.MeshBasicMaterial({ color: 0xfff4c0 }), tailMat = new THREE.MeshBasicMaterial({ color: 0xd42020 });
  const amberMat = new THREE.MeshBasicMaterial({ color: 0xf08a20 }), reflMat = new THREE.MeshBasicMaterial({ color: 0xa81818 });
  const MATS = [paint, glass, dark], P = 0, G = 1, D = 2;         // номера материалов для pick

  // Треугольники копятся по материалам и в конце становятся одной сеткой на материал.
  const soup = new Map(), loose = [];
  const bin = (mat) => soup.get(mat) || soup.set(mat, []).get(mat);
  const mid = (r) => r.reduce((c, p) => [c[0] + p[0] / r.length, c[1] + p[1] / r.length, c[2] + p[2] / r.length], [0, 0, 0]);
  const tri = (dst, a, b, c, o) => {                              // обход выставляется наружу от точки o внутри тела
    const ux = b[0] - a[0], uy = b[1] - a[1], uz = b[2] - a[2], vx = c[0] - a[0], vy = c[1] - a[1], vz = c[2] - a[2];
    const g = mid([a, b, c]);
    const outward = (uy * vz - uz * vy) * (g[0] - o[0]) + (uz * vx - ux * vz) * (g[1] - o[1]) + (ux * vy - uy * vx) * (g[2] - o[2]);
    dst.push(...a, ...(outward < 0 ? c : b), ...(outward < 0 ? b : c));
  };
  const geoOf = (v) => {                                          // у граней нет общих вершин — освещение гранёное
    const geo = new THREE.BufferGeometry();
    geo.setAttribute('position', new THREE.Float32BufferAttribute(v, 3));
    geo.computeVertexNormals();
    return geo;
  };
  // обшивка: rings[i] — замкнутый контур точек [x, y, z]; клетка (i, j) — между сечениями i, i+1 и точками j, j+1.
  // pick(i, j) -> [материал первого треугольника клетки, второго, другая диагональ]; cap — материал торцов (-1 — без них).
  // sym: диагонали клеток зеркальны слева и справа (поперёк контура).
  const loft = (rings, pick, cap = P, sym = false) => {
    const cs = rings.map(mid), n = rings.length;
    for (let i = 0; i + 1 < n; i++) {
      const A = rings[i], B = rings[i + 1], o = mid([cs[i], cs[i + 1]]);
      for (let j = 0; j < A.length; j++) {
        const k = (j + 1) % A.length, [m0, m1, f] = pick ? pick(i, j) : [P, P];
        const flip = f !== undefined ? f : sym && j >= (A.length - 1) / 2;
        if (flip) { tri(bin(MATS[m0]), A[j], B[j], B[k], o); tri(bin(MATS[m1]), A[j], B[k], A[k], o); }
        else { tri(bin(MATS[m0]), A[j], B[j], A[k], o); tri(bin(MATS[m1]), B[j], B[k], A[k], o); }
      }
    }
    if (cap >= 0) for (const [e, o] of [[0, cs[1]], [n - 1, cs[n - 2]]]) {     // торцы — веером от середины
      const R = rings[e];
      for (let j = 0; j < R.length; j++) tri(bin(MATS[cap]), cs[e], R[j], R[(j + 1) % R.length], o);
    }
  };
  const lerp = (a, b, t) => a + (b - a) * t;

  // --- кузов. Полусечение от пояса к оси: пояс, подоконник, верх окна (стойка), край верхнего стекла, крыша, ось.
  // Капот и корма — дуга эллипса DOME; кабина задаётся явно: подоконник (Ws, S), верх окна (Wc, G), край стекла (Wg, R).
  // c — доля кабины в переходных сечениях за задним стеклом; bow — на сколько середина сечения сдвинута по z (стекло выгнуто).
  const CAB = [[1, 0], [0.96, 0.07], [0.72, 0.78], [0.63, 0.92], [0.33, 0.985], [0, 1]];
  const DOME = [[1, 0], [0.966, 0.259], [0.766, 0.643], [0.5, 0.866], [0.208, 0.978], [0, 1]];
  //             z     полушир. пояс  верх   низ: полушир., высота | c  или  Ws     S      Wc     G      Wg     R      bow
  const SECT = [[-1.88,  0.47, 0.500, 0.555, 0.44, 0.42, 0],     //  0 передняя кромка капота, над бампером
                [-1.74,  0.49, 0.570, 0.635, 0.46, 0.34, 0],
                [-1.45,  0.51, 0.650, 0.722, 0.48, 0.24, 0],     //  капот ниже крыльев и лежит между ними
                [-1.15,  0.53, 0.730, 0.795, 0.50, 0.20, 0],
                [-0.88,  0.58, 0.795, 0.850, 0.54, 0.19, 0],
                [-0.62,  0.78, 0.820, 0.900, 0.76, 0.19, 0.750, 0.856, 0.690, 0.876, 0.630, 0.886, -0.08],  //  5 низ лобового — сразу за передним колесом
                [-0.47,  0.78, 0.820, 1.000, 0.76, 0.19, 0.745, 0.857, 0.700, 0.972, 0.635, 0.985, -0.06],  //  6 передний угол дверного стекла
                [-0.28,  0.78, 0.820, 1.150, 0.76, 0.19, 0.745, 0.856, 0.635, 1.102, 0.585, 1.125, -0.04],
                [-0.10,  0.78, 0.820, 1.280, 0.76, 0.19, 0.745, 0.855, 0.572, 1.188, 0.520, 1.240, -0.015], //  8 верх лобового
                [-0.01,  0.78, 0.820, 1.302, 0.76, 0.19, 0.745, 0.854, 0.566, 1.192, 0.500, 1.266, 0],
                [ 0.12,  0.78, 0.820, 1.311, 0.76, 0.19, 0.745, 0.853, 0.562, 1.193, 0.500, 1.276, 0],      // 10 макушка крыши
                [ 0.32,  0.78, 0.820, 1.305, 0.76, 0.19, 0.745, 0.850, 0.560, 1.190, 0.500, 1.270, 0],
                // от макушки к корме скат выпуклый: каждый следующий отрезок круче предыдущего
                [ 0.575, 0.78, 0.820, 1.284, 0.76, 0.19, 0.745, 0.846, 0.562, 1.172, 0.500, 1.250, 0],      // 12-13 средняя стойка
                [ 0.625, 0.78, 0.820, 1.278, 0.76, 0.19, 0.745, 0.846, 0.564, 1.165, 0.500, 1.243, 0],
                [ 0.76,  0.775, 0.820, 1.256, 0.72, 0.19, 0.742, 0.847, 0.575, 1.128, 0.500, 1.220, 0],     // 14 верх заднего стекла
                [ 0.90,  0.76, 0.822, 1.213, 0.60, 0.20, 0.730, 0.852, 0.600, 1.080, 0.505, 1.176, 0],
                [ 1.04,  0.73, 0.826, 1.156, 0.58, 0.21, 0.705, 0.868, 0.630, 1.020, 0.515, 1.120, 0],
                [ 1.16,  0.70, 0.832, 1.106, 0.58, 0.22, 0.680, 0.918, 0.665, 0.930, 0.525, 1.072, 0],      // 17 острый конец бокового стекла, над задней осью
                [ 1.30,  0.67, 0.850, 1.048, 0.56, 0.24, 0.6],
                [ 1.40,  0.65, 0.850, 1.006, 0.56, 0.25, 0.4],   // 19 низ заднего стекла
                [ 1.58,  0.62, 0.800, 0.928, 0.54, 0.24, 0.1],   // крышка мотора
                [ 1.80,  0.59, 0.730, 0.840, 0.52, 0.24, 0],
                [ 1.95,  0.57, 0.650, 0.740, 0.52, 0.26, 0],
                [ 2.06,  0.56, 0.560, 0.630, 0.52, 0.29, 0]];    // 23 корма: торец — задняя панель
  const half = (s) => {
    const [, W, M, T] = s;
    if (s.length > 7) { const [Ws, S, Wc, Gy, Wg, R] = s.slice(6); return [[W, M], [Ws, S], [Wc, Gy], [Wg, R], [Wg * 0.56, lerp(R, T, 0.72)], [0, T]]; }
    return CAB.map(([u, v], j) => [W * lerp(DOME[j][0], u, s[6]), M + (T - M) * lerp(DOME[j][1], v, s[6])]);
  };
  const HALF = SECT.map((s) => [[s[4], s[5]], ...half(s)]);
  const at = (z) => {                                             // полусечение на произвольном z
    let i = 0;
    while (i < SECT.length - 2 && z > SECT[i + 1][0]) i++;
    const t = Math.min(1, Math.max(0, (z - SECT[i][0]) / (SECT[i + 1][0] - SECT[i][0])));
    return HALF[i].map(([x, y], j) => [lerp(x, HALF[i + 1][j][0], t), lerp(y, HALF[i + 1][j][1], t)]);
  };
  const topY = (x, z) => {                                        // высота верха кузова над точкой (x, z)
    const h = at(z), ax = Math.abs(x);
    for (let j = 1; j < 6; j++) if (ax >= h[j + 1][0]) return lerp(h[j][1], h[j + 1][1], Math.max(0, (h[j][0] - ax) / (h[j][0] - h[j + 1][0] || 1)));
    return h[6][1];
  };
  const sideX = (y, z) => {                                       // полуширина борта на высоте y
    const h = at(z);
    for (let j = 0; j < 3; j++) if (y <= h[j + 1][1]) return lerp(h[j][0], h[j + 1][0], Math.max(0, (y - h[j][1]) / (h[j + 1][1] - h[j][1] || 1)));
    return h[3][0];
  };
  const rings = SECT.map((s, i) => {
    const h = HALF[i], bow = s[12] || 0;
    return [...h, ...h.slice(0, -1).reverse().map(([x, y]) => [-x, y])].map(([x, y]) => [x, y, s[0] + bow * (1 - (x / s[1]) ** 2)]);
  });
  // точки контура: 0 низ, 1 пояс, 2 подоконник, 3 верх окна, 4 край стекла, 5 крыша, 6 ось, дальше зеркально (7..12)
  const sideWin = (j) => j === 2 || j === 9, topWin = (j) => j >= 4 && j <= 7;
  loft(rings, (i, j) => {
    if (j === 12) return [D, D];                                                    // днище
    if (((i >= 5 && i <= 7) || (i >= 14 && i <= 18)) && topWin(j)) return [G, G];   // лобовое и заднее стёкла
    if (sideWin(j)) {
      if (i === 6) return j === 2 ? [P, G] : [G, P, true];                          // передний край дверного — косой, вдоль стойки
      if ((i >= 7 && i <= 11) || (i >= 13 && i <= 16)) return [G, G];               // дверное и заднее боковое, между ними стойка
      if (i === 12) return [D, D];
    }
    return [P, P];
  }, P, true);

  // --- крылья. Сечение — дуга от внутреннего края xi (утоплен в кузов) через гребень xc к внешнему краю xo,
  // снизу закрыта. Над колесом низ крыла поднят полуэллипсом rz × ry — колёсная арка.
  const ARCH_K = [-1, -0.8, -0.42, 0, 0.42, 0.8, 1];
  const arch = (zc, rz, ry, tops, xo, xi, xc) => ARCH_K.map((k, n) =>
    [zc + k * rz, PORSCHE_WHEEL_R + ry * Math.sqrt(1 - k * k), tops[n], xo[n], xi, xc]);
  //              z       низ    верх   xo     xi    xc
  const FRONT = [[-1.725, 0.50,  0.575, 0.725, 0.50, 0.615],      // нос крыла: от него вверх-назад — скос под фару
                 [-1.675, 0.46,  0.680, 0.765, 0.47, 0.615],
                 [-1.635, 0.42,  0.770, 0.795, 0.45, 0.620],
                 [-1.56,  0.34,  0.790, 0.812, 0.44, 0.630],
                 ...arch(-PORSCHE_AXLE, 0.335, 0.345, [0.797, 0.803, 0.820, 0.834, 0.845, 0.853, 0.857], [0.818, 0.822, 0.826, 0.826, 0.824, 0.818, 0.812], 0.43, 0.65),
                 [-0.73,  0.19,  0.862, 0.800, 0.42, 0.66],
                 [-0.62,  0.19,  0.868, 0.782, 0.42, 0.67],
                 [-0.50,  0.19,  0.850, 0.755, 0.42, 0.67]];      // гребень уходит в основание лобового, борт — в дверь
  // Заднее крыло — не «труба», а раструб: гребень прижат к кузову у подоконника, от него поверхность полого
  // спускается наружу и шире всего у кромки арки; к двери и к корме раструб сходит на нет.
  const REAR = [[0.55,  0.19, 0.60,  0.755, 0.45, 0.64],          // раструб вырастает из борта за дверью
                [0.64,  0.19, 0.79,  0.805, 0.45, 0.65],
                [0.72,  0.19, 0.835, 0.850, 0.45, 0.66],
                ...arch(PORSCHE_AXLE, 0.36, 0.30, [0.848, 0.853, 0.860, 0.862, 0.860, 0.855, 0.850], [0.868, 0.878, 0.886, 0.8875, 0.886, 0.880, 0.874], 0.45, 0.66).map((p, n) => n === 6 ? [p[0], 0.25, ...p.slice(2)] : p),   // за колесом низ не поднимается
                [1.60,  0.24, 0.838, 0.868, 0.45, 0.65],
                [1.80,  0.24, 0.800, 0.840, 0.45, 0.62],
                [1.92,  0.25, 0.705, 0.800, 0.45, 0.60],
                [2.00,  0.27, 0.610, 0.745, 0.45, 0.58],
                [2.065, 0.29, 0.560, 0.670, 0.45, 0.56]];         // корма уже арок и скруглена в плане; торец — под фонарь
  for (const sx of [-1, 1]) for (const st of [FRONT, REAR]) {
    loft(st.map(([z, yb, yt, xo, xi, xc]) => {
      const r = [];
      for (let j = 0; j <= 6; j++) {
        const a = j * Math.PI / 6, co = Math.cos(a);
        r.push([sx * (xc + (co > 0 ? xo - xc : xc - xi) * co), yb + (yt - yb) * Math.pow(Math.sin(a), 0.7), z]);
      }
      return r;
    }));
  }

  // --- бамперы, юбка и «китовый хвост» — плиты со скошенными рёбрами; к концу сужаются, углы в плане срезаны
  const slab = ([z, W, yb, yt], r = 0.04) =>
    [[W, yb + r], [W, yt - r], [W - r, yt], [-W + r, yt], [-W, yt - r], [-W, yb + r], [-W + r, yb], [W - r, yb]].map(([x, y]) => [x, y, z]);
  const skin = (rows, r) => loft(rows.map((s) => slab(s, r)));
  // бамперы скруглены в плане: FB, VB, RB — таблицы [полуширина, z] от середины к углу
  const FB = [[0.22, -2.04], [0.44, -2.015], [0.6, -1.965], [0.72, -1.9], [0.8, -1.82], [0.835, -1.72], [0.835, -1.64]];
  const VB = [[0.22, -1.98], [0.44, -1.955], [0.6, -1.91], [0.72, -1.85], [0.79, -1.78], [0.815, -1.68], [0.815, -1.48]];
  const RB = [[0.26, 2.245], [0.48, 2.225], [0.64, 2.185], [0.76, 2.125], [0.84, 2.04], [0.868, 1.94], [0.868, 1.86]];
  const tab = (T, x) => {                                         // z поверхности бампера на полуширине x
    let i = 0;
    while (i < T.length - 2 && x > T[i + 1][0]) i++;
    return x <= T[0][0] ? T[0][1] : lerp(T[i][1], T[i + 1][1], Math.min(1, (x - T[i][0]) / (T[i + 1][0] - T[i][0])));
  };
  skin(FB.map(([w, z]) => [z, w, 0.32, 0.47]));                   // передний бампер — выступает дальше фар
  skin(VB.map(([w, z]) => [z, w, 0.17, 0.34]));                   // юбка под ним
  skin(RB.map(([w, z]) => [z, w, 0.33, 0.47]));                   // задний бампер
  skin([[1.56, 0.44, 0.880, 0.905], [1.66, 0.68, 0.878, 0.905], [2.03, 0.715, 0.880, 0.915]], 0.012);                                                        // плита хвоста
  const wedge = ([z, Wt, yt, Wb, yb]) => [[Wt, yt], [-Wt, yt], [-Wb, yb], [Wb, yb]].map(([x, y]) => [x, y, z]);
  loft([[1.60, 0.40, 0.89, 0.36, 0.86], [1.78, 0.58, 0.89, 0.50, 0.75], [1.96, 0.62, 0.89, 0.58, 0.79], [2.02, 0.60, 0.89, 0.56, 0.85]].map(wedge));    // основание под ней

  // --- детали. part — брусок; rod — брусок сечением w × h между двумя точками; patch — плоская накладка-многоугольник
  const part = (w, h, d, mat, x, y, z) => { const m = new THREE.Mesh(new THREE.BoxGeometry(w, h, d), mat); m.position.set(x, y, z); loose.push(m); return m; };
  const rod = (a, b, w, h, mat) => {
    const A = new THREE.Vector3(...a), B = new THREE.Vector3(...b), m = part(w, h, A.distanceTo(B), mat, 0, 0, 0);
    m.position.copy(A).add(B).multiplyScalar(0.5);
    m.quaternion.setFromUnitVectors(new THREE.Vector3(0, 0, 1), B.sub(A).normalize());
    return m;
  };
  const patch = (pts, mat) => { for (let k = 1; k + 1 < pts.length; k++) tri(bin(mat), pts[0], pts[k], pts[k + 1], [0, 0.5, 0]); };
  const sidePt = (sx, y, z, d = 0.006) => [sx * (sideX(y, z) + d), y, z];
  const seamLine = (sx, pts, w = 0.02) => { for (let k = 0; k + 1 < pts.length; k++) rod(sidePt(sx, ...pts[k]), sidePt(sx, ...pts[k + 1]), 0.014, w, seam); };

  // хвост: чёрная резиновая кромка по заднему краю и бокам; на плите — решётка мотора
  rod([-0.735, 0.905, 2.035], [0.735, 0.905, 2.035], 0.06, 0.09, dark);
  rod([0, 0.911, 1.69], [0, 0.918, 1.92], 0.98, 0.012, dark);
  for (const z of [1.75, 1.81, 1.87]) part(0.92, 0.012, 0.02, seam, 0, 0.918 + (z - 1.69) * 0.03, z);
  // задняя панель: катафот между фонарями, прямо над бампером; задний бампер: чёрная полоса и номер
  part(0.84, 0.10, 0.03, reflMat, 0, 0.53, 2.07);
  part(0.52, 0.04, 0.02, dark, 0, 0.40, 2.25);
  part(0.42, 0.11, 0.02, plate, 0, 0.405, 2.256);
  part(0.16, 0.035, 0.02, dark, -0.27, topY(0.27, 1.99) + 0.004, 1.99).rotation.x = 0.6;       // шильдик «turbo» на крышке
  part(0.06, 0.05, 0.05, tailMat, -0.56, 0.30, 2.2);                                             // задний противотуманный фонарь под бампером
  rod([0.02, topY(0, 1.385) + 0.016, 1.385], [-0.3, topY(0.3, 1.2) + 0.016, 1.2], 0.02, 0.016, dark);   // задний дворник
  // передний бампер: чёрная полоса; в юбке — номер и противотуманки, снизу чёрная губа
  part(0.46, 0.045, 0.02, dark, 0, 0.40, -2.044);
    part(0.42, 0.10, 0.02, plate, 0, 0.265, -1.984);
  for (let k = 0; k + 1 < VB.length - 1; k++) for (const sx of [-1, 1]) rod([sx * VB[k][0], 0.165, VB[k][1] + 0.03], [sx * VB[k + 1][0], 0.165, VB[k + 1][1] + 0.03], 0.09, 0.04, dark);
  part(0.46, 0.04, 0.09, dark, 0, 0.165, -1.95);
  // дворники на кромке капота перед лобовым
  rod([-0.52, topY(0.52, -0.67) + 0.014, -0.655], [-0.06, topY(0.06, -0.72) + 0.014, -0.705], 0.022, 0.016, dark);
  rod([0.0, topY(0, -0.72) + 0.014, -0.705], [0.46, topY(0.46, -0.68) + 0.014, -0.665], 0.022, 0.016, dark);
  for (const sx of [-1, 1]) for (const [za, zb] of [[-1.62, -1.3], [-1.3, -1.0], [-1.0, -0.76]])                // швы капота вдоль крыльев
    rod([sx * 0.415, topY(0.415, za) + 0.004, za], [sx * 0.415, topY(0.415, zb) + 0.004, zb], 0.022, 0.012, seam);
  part(0.36, 0.01, 0.04, seam, 0, topY(0, -0.76) + 0.003, -0.76);                               // решётка воздухозаборника у лобового
  part(0.05, 0.012, 0.06, chrome, 0, topY(0, -1.72) + 0.004, -1.72);                            // герб на капоте
  for (const sx of [-1, 1]) {
    rod([sx * 0.69, 0.897, 1.66], [sx * 0.725, 0.908, 2.05], 0.05, 0.07, dark);                // боковая кромка хвоста
    rod([sx * 0.44, 0.90, 1.565], [sx * 0.69, 0.90, 1.665], 0.04, 0.04, dark);
    // фара лежит на скосе носа крыла: большой хромовый ободок, стекло смотрит вперёд-вверх
    const rim = new THREE.CylinderGeometry(0.126, 0.126, 0.06, 14).rotateX(Math.PI / 2).rotateX(0.46).translate(sx * 0.615, 0.672, -1.70);
    const lens = new THREE.CircleGeometry(0.108, 14).rotateY(Math.PI).translate(0, 0, -0.031).rotateX(0.46).translate(sx * 0.615, 0.672, -1.70);
    loose.push(new THREE.Mesh(rim, chrome), new THREE.Mesh(lens, lensMat));
    for (let k = 0; k < 4; k++) rod([sx * FB[k][0], 0.40, FB[k][1] - 0.006], [sx * FB[k + 1][0], 0.40, FB[k + 1][1] - 0.006], 0.02, 0.045, k === 2 ? amberMat : dark);   // чёрная полоса бампера,           // поворотник на углу бампера
    rod([sx * 0.44, 0.27, tab(VB, 0.44) - 0.008], [sx * 0.60, 0.27, tab(VB, 0.60) - 0.008], 0.02, 0.06, lensMat);                                  // противотуманка
    part(0.03, 0.14, 0.13, dark, sx * 0.838, 0.40, -1.60);                                      // гармошки бамперов
    part(0.03, 0.14, 0.12, dark, sx * 0.862, 0.40, 1.83);
    part(0.10, 0.19, 0.09, dark, sx * 0.34, 0.405, 2.245);                                        // клыки
    part(0.17, 0.10, 0.04, tailMat, sx * 0.49, 0.53, 2.072);                                  // фонарь
    part(0.03, 0.10, 0.045, lensMat, sx * 0.565, 0.53, 2.07);                                 // фонарь заднего хода
    part(0.12, 0.10, 0.045, amberMat, sx * 0.63, 0.53, 2.062);
    for (let k = 0; k < 5; k++) rod([sx * RB[k][0], 0.40, RB[k][1] + 0.006], [sx * RB[k + 1][0], 0.40, RB[k + 1][1] + 0.006], 0.02, 0.04, dark);   // чёрная полоса заднего бампера                                // поворотник огибает угол —
    rod([sx * 0.80, 0.53, 1.90], [sx * 0.675, 0.53, 2.075], 0.03, 0.10, amberMat);           // виден и сбоку
    part(0.025, 0.045, 1.26, dark, sx * (sideX(0.27, 0) + 0.008), 0.27, -0.08);                 // чёрный порог
    part(0.03, 0.035, 0.03, amberMat, sx * 0.812, 0.70, -0.76);                                 // повторитель на крыле
    // швы двери, ручка
    seamLine(sx, [[0.845, 0.575], [0.67, 0.56], [0.49, 0.495], [0.385, 0.425], [0.325, 0.355], [0.305, 0.27], [0.30, -0.61], [0.65, -0.64], [0.76, -0.628], [0.815, -0.59], [0.845, -0.53]]);
    part(0.03, 0.035, 0.2, dark, sx * (sideX(0.715, 0.45) + 0.012), 0.715, 0.445);
    // зеркало-«флажок» на ножке
    part(0.06, 0.125, 0.18, paint, sx * 0.89, 0.90, -0.25);
    part(0.11, 0.03, 0.04, paint, sx * 0.815, 0.865, -0.27);
    rod([sx * 0.557, 1.2, -0.06], [sx * 0.565, 1.178, 0.6], 0.016, 0.016, seam);                // водосток над дверью
    // тёмные ниши арок за колёсами
    part(0.30, 0.42, 0.62, dark, sx * 0.585, 0.44, -PORSCHE_AXLE);
    part(0.32, 0.38, 0.68, dark, sx * 0.62, 0.42, PORSCHE_AXLE);
  }
  part(0.13, 0.012, 0.12, paint, -0.67, 0.862, -0.84);                                          // лючок бензобака на левом крыле
  for (const sx of [-1, 1]) {                                                                   // две выхлопные трубы — по одной с каждой стороны, тёмный графит
    const pipe = new THREE.Mesh(new THREE.CylinderGeometry(0.04, 0.04, 0.16, 8).rotateX(Math.PI / 2), lambert({ color: 0x2f3236 }));
    pipe.position.set(sx * 0.45, 0.27, 2.17); loose.push(pipe);
  }

  for (const m of loose) {                                        // бруски вливаются в общие сетки своих материалов
    m.updateMatrix();
    bin(m.material).push(...m.geometry.toNonIndexed().applyMatrix4(m.matrix).attributes.position.array);
  }
  soup.forEach((v, mat) => body.add(new THREE.Mesh(geoOf(v), mat)));

  // колёса Fuchs: шина с боковиной, полированный обод, чёрный центр из пяти лепестков — видно, как крутится; задние шире
  const cyl = (r, w, n) => new THREE.CylinderGeometry(r, r, w, n).rotateZ(Math.PI / 2);
  const weld = (...geos) => {                                     // несколько геометрий в одну, нормали сохраняются
    const pos = [], nor = [];
    for (const g of geos) { const q = g.toNonIndexed(); pos.push(...q.attributes.position.array); nor.push(...q.attributes.normal.array); }
    const geo = new THREE.BufferGeometry();
    geo.setAttribute('position', new THREE.Float32BufferAttribute(pos, 3));
    geo.setAttribute('normal', new THREE.Float32BufferAttribute(nor, 3));
    return geo;
  };
  const petal = (k) => new THREE.BoxGeometry(1.03, 0.085, 0.13).translate(0, 0, 0.11).rotateX(k * Math.PI * 0.4);
  const blackGeo = weld(cyl(PORSCHE_WHEEL_R, 1, 14), cyl(0.085, 1.035, 8), ...[0, 1, 2, 3, 4].map(petal));
  const wallGeo = cyl(0.27, 1.01, 14), rimGeo = cyl(0.215, 1.02, 14);
  const wallMat = lambert({ color: 0x2b2c2e });
  const front = [], spin = [];
  for (const [z, x, w] of [[-PORSCHE_AXLE, 0.695, 0.2], [PORSCHE_AXLE, 0.75, 0.25]]) for (const sx of [-1, 1]) {
    const pivot = new THREE.Group(), wheel = new THREE.Group();
    pivot.position.set(sx * x, PORSCHE_WHEEL_R, z);
    for (const [geo, mat] of [[blackGeo, dark], [wallGeo, wallMat], [rimGeo, chrome]]) { const m = new THREE.Mesh(geo, mat); m.scale.x = w; wheel.add(m); }
    pivot.add(wheel); car.add(pivot); spin.push(wheel);
    if (z < 0) front.push(pivot);
  }
  car.userData.frontWheels = front;
  car.userData.spin = spin;
  car.userData.body = body;
  return car;
}
