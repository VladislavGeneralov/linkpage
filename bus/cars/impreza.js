    rod([sx * (BODY[8][5] + 0.008), 0.932, 0.243], [sx * (BODY[8][7] + 0.01), 1.298, 0.29], 0.014, 0.06, MATS[GLOSS]);
    patch([[sx * (BODY[11][7] + 0.01), 1.298, 0.84], [sx * (BODY[12][7] + 0.01), 0.99, 1.005], [sx * (BODY[13][7] + 0.01), 0.982, 1.14]], dark);
