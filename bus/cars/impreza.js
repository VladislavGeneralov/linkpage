    tsheet(TAIL_C.map(([a, t, b], i) => [sx * (a - (i ? 0 : 0.012)), t + 0.012, b - 0.012]), seam, 0.004);
    tsheet(TAIL_C.map(([a, t, b]) => [sx * a, t, b]), tailMat, 0.009);
