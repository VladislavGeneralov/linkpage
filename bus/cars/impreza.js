    // заглушка противотуманки — скруглённая ниша: прямой верх, отвесный внутренний край, наружный низ — большая дуга;
    // тёмная кромка, внутри панель в цвет кузова с розовым «STi» и вертикальной щелью
    const POCK = [[0.418, 0.416, 0.258], [0.47, 0.416, 0.256], [0.55, 0.415, 0.256], [0.62, 0.413, 0.262], [0.68, 0.411, 0.28], [0.72, 0.409, 0.305], [0.745, 0.407, 0.335], [0.755, 0.405, 0.37]];
    sheet(POCK.map(([a, t, b]) => [sx * a, t, b]), 2, dark, 0.004);
    sheet(POCK.map(([a, t, b], i) => [sx * lerp(0.43, 0.742, (a - 0.418) / 0.337), t - 0.012, b + 0.013 + (i > 5 ? 0.006 : 0)]), 2, paint, 0.009);
    sheet([0.54, 0.60, 0.66].map((a) => [sx * a, 0.385, 0.36]), 2, pink, 0.013);
    sheet([0.503, 0.514].map((a) => [sx * a, 0.395, 0.29]), 2, dark, 0.012);
    // фонарь заходит на крыло
    // задний фонарь (по наложению на фото сзади): верх поднимается к углу кузова, внутренний конец сужается клином к низу
